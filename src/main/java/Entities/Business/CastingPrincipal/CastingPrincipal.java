package entities.business.CastingPrincipal;

public class CastingPrincipal {
    private Long idCasting;
    private String filmId;
    private String acteurId;

    public Long getIdCasting() { return idCasting; }
    public void setIdCasting(Long value) { this.idCasting = value; }
    public String getFilmId() { return filmId; }
    public void setFilmId(String value) { this.filmId = value; }
    public String getActeurId() { return acteurId; }
    public void setActeurId(String value) { this.acteurId = value; }
}
